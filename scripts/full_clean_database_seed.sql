    0 AS sold,
    1 AS revision,
    NOW(),
    NOW()
FROM product_variants;

-- Stock for products WITHOUT variants
INSERT INTO stocks (id, product_id, variant_id, total, available, reserved, sold, revision, created_at, updated_at)
SELECT
    gen_random_uuid(),
    id AS product_id,
    NULL AS variant_id,
    50 AS total,
    50 AS available,
    0 AS reserved,
    0 AS sold,
    1 AS revision,
    NOW(),
    NOW()
FROM products p
WHERE NOT EXISTS (
    SELECT 1 FROM product_variants pv WHERE pv.product_id = p.id
);